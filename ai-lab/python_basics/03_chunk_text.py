# ---- 1. 函数可以有默认参数 ----
def chunk_text(text, chunk_size=200, overlap=50):
    """
    把长文本切成带重叠的小块。

    text:       要切的完整文本
    chunk_size: 每块多少字符
    overlap:    相邻块之间重叠多少字符

    返回：字符串列表

    为什么需要重叠？
        不重叠：[------块1------][------块2------]
                              ↑ 一句话被从中间切断，两块的语义都不完整
        有重叠：[------块1------]
                        [------块2------]
                        ↑ 交界处的内容在两块里都出现，检索时不会丢
    """
    chunks = []              # 空列表
    start = 0                # 起始位置

    while start < len(text):
        end = start + chunk_size
        chunk = text[start:end]          # 切片：取从 start 到 end（不含 end）
        chunks.append(chunk)
        start = end - overlap            # 回退 overlap 个字符

    return chunks


def clean_text(text):
    """
    把连续的空白字符压缩成一个空格（真实文档里到处是换行和多余空格）。
    """
    return " ".join(text.split())
    # text.split()     不加参数时按任意空白分割，并自动去掉空串
    # " ".join(列表)   用空格把列表重新拼成字符串（注意和 JS 的 join 顺序相反）


# ---- 2. 准备一段测试文本（真实项目里这里会是从 PDF 解析出来的内容）----
sample = """
大语言模型的应用开发与传统的 Web 开发有一个根本区别：
传统应用的输出是确定的，而大模型的输出是概率性的。

这意味着两件事。第一，你无法用传统单元测试来验证输出是否正确，
必须引入评估体系，用统计指标衡量效果。第二，产品设计必须考虑
不确定性，比如让用户能重新生成、能看到引用来源、能一键纠正。

另一个区别是成本。每次调用都有 token 成本，上下文越长越贵。
所以工程上必须考虑：怎么压缩上下文、怎么做缓存、怎么给简单问题
分配小模型。这些都不是模型能力问题，而是工程问题。

这也是为什么前端背景的人在这个方向上有优势：
交互设计、流式渲染、状态管理，这些恰恰是纯算法背景的人不擅长的。
"""


# ---- 3. 主程序 ----
if __name__ == "__main__":        # Python 的入口判断：只有直接运行本文件时才执行
    cleaned = clean_text(sample)
    print(f"原文长度：{len(sample)} 字符")
    print(f"清洗后长度：{len(cleaned)} 字符")
    print()

    chunks = chunk_text(cleaned, chunk_size=120, overlap=30)
    print(f"切成 {len(chunks)} 块，每块 120 字符，重叠 30 字符")
    print()

    # ---- 4. enumerate：同时拿到下标和元素（相当于 JS 的 entries()）----
    for i, chunk in enumerate(chunks):
        print(f"--- 第 {i + 1} 块（{len(chunk)} 字符）---")
        print(chunk)
        print()
